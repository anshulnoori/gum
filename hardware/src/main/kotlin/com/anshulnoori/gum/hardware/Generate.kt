@file:JvmName("Generate")

package com.anshulnoori.gum.hardware

import java.io.File
import java.net.URLClassLoader
import kotlin.system.exitProcess

/**
 * Build-time entry point for the Gum Gradle plugin.
 * Arguments: compiled hardware classes, resource output directory, Java output directory, app namespace.
 *
 * Finds the one [RobotConfig] object, writes `xml/<name>.xml`, and writes a Java hook that the
 * Robot Controller calls at app start to activate that configuration.
 */
fun main(args: Array<String>) {
    require(args.size == 4) { "Usage: Generate <classes> <resOut> <javaOut> <namespace>" }
    val (classesDir, resOut, javaOut, namespace) = args.map { it }
    val config = try {
        findConfig(File(classesDir)).also { it.toXml() }
    } catch (error: IllegalArgumentException) {
        System.err.println("Gum robot configuration: ${error.message}")
        exitProcess(1)
    } catch (error: IllegalStateException) {
        System.err.println("Gum robot configuration: ${error.message}")
        exitProcess(1)
    }

    File(resOut, "xml/${config.name}.xml").apply {
        parentFile.mkdirs()
        writeText(config.toXml())
    }
    File(javaOut, "com/anshulnoori/gum/generated/GumRobotConfig.java").apply {
        parentFile.mkdirs()
        writeText(activationHook(config.name, namespace))
    }
}

private fun findConfig(classesDir: File): RobotConfig {
    val loader = URLClassLoader(arrayOf(classesDir.toURI().toURL()), RobotConfig::class.java.classLoader)
    val configs = classesDir.walk()
        .filter { it.isFile && it.extension == "class" }
        .map { it.relativeTo(classesDir).path.removeSuffix(".class").replace(File.separatorChar, '.') }
        .map { Class.forName(it, false, loader) }
        .filter { RobotConfig::class.java.isAssignableFrom(it) && it != RobotConfig::class.java }
        .toList()
    val config = configs.singleOrNull()
        ?: error("Expected one RobotConfig object in the hardware sources, found ${configs.map { it.name }}")
    val instance = runCatching { config.getField("INSTANCE") }.getOrNull()
        ?: error("${config.name} must be a Kotlin object")
    return try {
        instance.get(null) as RobotConfig
    } catch (error: ExceptionInInitializerError) {
        // Declaration checks fail while the object initializes; report the check, not the wrapper.
        throw error.cause ?: error
    }
}

private fun activationHook(name: String, namespace: String) = """
    |// Generated by the Gum Gradle plugin from the RobotConfig in src/hardware. Do not edit.
    |package com.anshulnoori.gum.generated;
    |
    |import android.content.Context;
    |import com.anshulnoori.gum.ftc.RobotConfigActivation;
    |import org.firstinspires.ftc.ftccommon.external.OnCreate;
    |
    |public final class GumRobotConfig {
    |    private GumRobotConfig() {}
    |
    |    /** Runs when the Robot Controller app starts, before it reads the active configuration. */
    |    @OnCreate
    |    public static void activate(Context context) {
    |        RobotConfigActivation.activate(context, "$name", $namespace.R.xml.$name);
    |    }
    |}
    |""".trimMargin()
