@file:JvmName("Generate")

package com.anshulnoori.gum.hardware

import java.io.File
import java.net.URLClassLoader
import kotlin.system.exitProcess

/**
 * Build-time entry point for the Gum Gradle plugin.
 * Arguments: compiled hardware classes, resource output directory, Java output directory,
 * Kotlin output directory, app namespace.
 *
 * Finds the one [RobotConfig] object, writes `xml/<name>.xml`, writes a Java hook that the
 * Robot Controller calls at app start to activate that configuration when its wiring is new, and
 * writes program builders typed to the `RobotGraph` in the config's package.
 */
fun main(args: Array<String>) {
    require(args.size == 5) { "Usage: Generate <classes> <resOut> <javaOut> <kotlinOut> <namespace>" }
    val (classesDir, resOut, javaOut, kotlinOut, namespace) = args
    val (config, xml) = try {
        findConfig(File(classesDir)).let { it to it.toXml() }
    } catch (error: IllegalArgumentException) {
        System.err.println("Gum robot configuration: ${error.message}")
        exitProcess(1)
    } catch (error: IllegalStateException) {
        System.err.println("Gum robot configuration: ${error.message}")
        exitProcess(1)
    }

    File(resOut, "xml/${config.name}.xml").apply {
        parentFile.mkdirs()
        writeText(xml)
    }
    File(javaOut, "com/anshulnoori/gum/generated/GumRobotConfig.java").apply {
        parentFile.mkdirs()
        writeText(activationHook(config.name, namespace, config.wiringHash()))
    }
    val pkg = config.javaClass.`package`?.name.orEmpty()
    File(kotlinOut, "${pkg.replace('.', '/')}/GumPrograms.kt".removePrefix("/")).apply {
        parentFile.mkdirs()
        // A nested object's binary name has a '$'; Kotlin source names it with dots.
        writeText(programBuilders(pkg, config.javaClass.name.replace('$', '.')))
    }
}

private fun findConfig(classesDir: File): RobotConfig {
    val loader = URLClassLoader(arrayOf(classesDir.toURI().toURL()), RobotConfig::class.java.classLoader)
    val configs = classesDir.walk()
        .filter { it.isFile && it.extension == "class" }
        .map { it.relativeTo(classesDir).path.removeSuffix(".class").replace(File.separatorChar, '.') }
        .map { Class.forName(it, false, loader) }
        .filter { RobotConfig::class.java.isAssignableFrom(it) && it != RobotConfig::class.java }
        .toList()
    val config = configs.singleOrNull()
        ?: error("Expected one RobotConfig object in the hardware sources, found ${configs.map { it.name }}")
    val instance = runCatching { config.getField("INSTANCE") }.getOrNull()
        ?: error("${config.name} must be a Kotlin object")
    return try {
        instance.get(null) as RobotConfig
    } catch (error: ExceptionInInitializerError) {
        // Declaration checks fail while the object initializes; report the check, not the wrapper.
        throw error.cause ?: error
    }
}

/**
 * `teleop`, `autonomous`, and `utility` in TeamCode's package, typed to its `RobotGraph` and
 * checked against [config] at INIT. Metro replaces `createGraph` only in source it compiles, so
 * these live in TeamCode.
 */
private fun programBuilders(pkg: String, config: String): String {
    val builder = { kind: String, what: String -> """
        |/** $what whose setup receives a new [RobotGraph] at each INIT. */
        |fun $kind(
        |    name: String,
        |    group: String = "",
        |    description: String = "",
        |    setup: FtcScope.(robot: RobotGraph) -> Any?,
        |): FtcProgram = program(ProgramKind.${kind.uppercase()}, name, group, description, $config, { createGraph<GumChainGraph>() }, GumChainGraph::robot, setup)
        |""".trimMargin() }
    return """
        |// Generated by the Gum Gradle plugin. Do not edit.
        |// Declare `@GraphExtension(OpModeScope::class) interface RobotGraph : Robot` in this package.
        |${if (pkg.isEmpty()) "" else "package $pkg\n"}
        |import com.anshulnoori.gum.core.ProgramKind
        |import com.anshulnoori.gum.ftc.ChainScope
        |import com.anshulnoori.gum.ftc.FtcProgram
        |import com.anshulnoori.gum.ftc.FtcScope
        |import com.anshulnoori.gum.ftc.program
        |import dev.zacsweers.metro.DependencyGraph
        |import dev.zacsweers.metro.createGraph
        |
        |/** Lives for one chain of programs; each run's [RobotGraph] extends it. */
        |@DependencyGraph(ChainScope::class)
        |interface GumChainGraph {
        |    fun robot(): RobotGraph
        |}
        |
        |""".trimMargin() + listOf(
        builder("teleop", "A TeleOp"),
        builder("autonomous", "An autonomous program"),
        builder("utility", "A utility program"),
    ).joinToString("\n")
}

private fun activationHook(name: String, namespace: String, wiring: String) = """
    |// Generated by the Gum Gradle plugin from the RobotConfig in src/hardware. Do not edit.
    |package com.anshulnoori.gum.generated;
    |
    |import android.content.Context;
    |import com.anshulnoori.gum.ftc.RobotConfigActivation;
    |import org.firstinspires.ftc.ftccommon.external.OnCreate;
    |
    |public final class GumRobotConfig {
    |    private GumRobotConfig() {}
    |
    |    /**
    |     * Runs when the Robot Controller app starts, before it reads the active configuration.
    |     * The last argument is a hash of the generated XML, so new wiring is activated once.
    |     */
    |    @OnCreate
    |    public static void activate(Context context) {
    |        RobotConfigActivation.activate(context, "$name", $namespace.R.xml.$name, "$wiring");
    |    }
    |}
    |""".trimMargin()
